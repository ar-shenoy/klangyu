function rowToTrack(row: Row): Track {
  const camelot = toCamelot(row.keyRoot, row.mode);
  return {
    ...row,
    albumArtist: row.artist,
    camelot,
    hue: keyHue(camelot),
    peaks: makePeaks(row.seed, row.energy),
    source: "sketch",
    analysis: "done",
    favourite: false,
    playCount: 0,
    skipCount: 0,
    lastPlayedAt: null,
    hidden: false,
    lyricOffsetMs: 0,
    mono: false,
  };
}

export function createCatalog(): Track[] {
  return ROWS.map(rowToTrack);
}

export function seedHistory(tracks: Track[], now = Date.now()): { tracks: Track[]; events: PlayEvent[] } {
  const next = tracks.map((t) => ({ ...t }));
  const picks = [0, 1, 5, 9, 10, 2, 6, 14, 8, 4, 3, 7, 11, 0, 9, 5, 15, 12, 1, 8, 10, 6, 2, 14];
  const hours = [8, 9, 8, 18, 19, 22, 23, 7, 12, 13, 18, 21, 22, 9, 19, 8, 17, 23, 12, 21, 7, 18, 22, 13];
  const events: PlayEvent[] = picks.map((ti, i) => {
    const track = next[ti % next.length];
    const completed = i % 7 !== 0;
    const startedAt = now - (i % 8) * 86_400_000 - hours[i] * 3_600_000;
    const playedMs = completed ? Math.min(track.durationMs - 8000, 150_000) : 12_000;
    return {
      id: `seed-${i}`,
      trackId: track.id,
      startedAt,
      playedMs,
      completed,
      hourOfDay: hours[i],
    };
  });
  for (const event of events) {
    const track = next.find((t) => t.id === event.trackId);
    if (!track) continue;
    if (event.completed) track.playCount += 1;
    else track.skipCount += 1;
    track.lastPlayedAt = Math.max(track.lastPlayedAt ?? 0, event.startedAt);
  }
  for (const id of ["nordkai", "yuetai", "sublevel"]) {
    const track = next.find((t) => t.id === id);
    if (track) track.favourite = true;
  }
  return { tracks: next, events };
}
